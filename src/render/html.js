const authorsHTML = (a) => esc(a).replace(/H\. Yin/g, '<strong>H. Yin</strong>');

function pubHTML(p) {
  const links = [];
  if (p.pdf) links.push(`<a href="${p.pdf}" target="_blank" rel="noopener">PDF</a>`);
  if (p.link) links.push(`<a href="${p.link}" target="_blank" rel="noopener">${esc(p.linkLabel || (p.link.includes('doi.org') ? 'DOI' : 'Link'))}</a>`);
  if (!p.pdf && !p.link) links.push(`<a href="${p.href}" target="_blank" rel="noopener">Find</a>`);
  if (p.code) links.push(`<a href="${p.code}" target="_blank" rel="noopener">Code</a>`);
  links.push(`<button type="button" class="pub__ask" data-ask-pub="${p.id}">Ask about this</button>`);
  const tags = (p.tags || []).map((t) => `<span class="tag">${esc(t)}</span>`).join('');
  return `
          <li class="pub" id="pub-${p.id}" data-theme="${p.theme}">
            <span class="pub__glyph">${glyph(p.theme, p.id)}</span>
            <div class="pub__body">
              <a class="pub__title" href="${p.href}" target="_blank" rel="noopener">${esc(p.title)}</a>
              <p class="pub__authors">${authorsHTML(p.authors)}</p>
              <p class="pub__venue">${esc(p.venue)}${tags}</p>
              <p class="pub__links">${links.join('')}</p>
            </div>
          </li>`;
}

function publicationsHTML() {
  const groups = new Map();
  for (const p of publications) {
    const k = p.year ? String(p.year) : 'In preparation';
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(p);
  }
  const keys = [...groups.keys()].sort((a, b) => (a === 'In preparation' ? -1 : b === 'In preparation' ? 1 : +b - +a));
  const counts = Object.fromEntries(themes.map((t) => [t.id, publications.filter((p) => p.theme === t.id).length]));
  const filters = [`<button type="button" class="filter" data-filter="all" aria-pressed="true">All <span>${publications.length}</span></button>`]
    .concat(themes.map((t) => `<button type="button" class="filter" data-filter="${t.id}" aria-pressed="false">${esc(t.label)} <span>${counts[t.id]}</span></button>`))
    .join('');
  return `
    <section class="pubs" id="publications" data-state="quiet" data-accent="#e8ab62" aria-labelledby="h-pubs">
      <div class="pubs__inner">
        <h2 class="section-title" id="h-pubs" data-strain data-text="Publications">Publications</h2>
        <p class="section-lede" data-reveal>${publications.length} works, from railway ballast to neural operators. First-author work is marked; every entry can be asked about.</p>
        <div class="filters" role="group" aria-label="Filter publications by theme" data-no-indent>${filters}</div>
        <div class="pubs__list">
          ${keys
            .map(
              (k) => `
          <div class="pubs__year" data-year-group>
            <h3 class="pubs__yearlabel">${esc(k)}</h3>
            <ol class="pubs__items">${groups.get(k).map(pubHTML).join('')}</ol>
          </div>`,
            )
            .join('')}
        </div>
      </div>
    </section>`;
}

function pathHTML() {
  const items = path
    .map(
      (p) => `
          <li class="step" data-ring="${p.from - 2012}" tabindex="0">
            <span class="step__years">${esc(p.years)}</span>
            <span class="step__role">${esc(p.role)}</span>
            <span class="step__place">${esc(p.place)}</span>
            ${p.detail ? `<span class="step__detail">${esc(p.detail)}</span>` : ''}
          </li>`,
    )
    .join('');
  const proj = projects
    .map((p) => `<li><span class="mini__title">${esc(p.title)}</span><span class="mini__meta">${esc(p.sponsor)} · ${esc(p.years)}</span><span class="mini__text">${esc(p.points.join(' '))}</span></li>`)
    .join('');
  const teach = teaching
    .map((t) => {
      const ev = t.pdf ? ` <a href="${t.pdf}" target="_blank" rel="noopener">evaluation</a>` : t.pdfs ? ' ' + t.pdfs.map((x) => `<a href="${x.href}" target="_blank" rel="noopener">${esc(x.label)}</a>`).join(' ') : '';
      return `<li><span class="mini__title">${esc(t.title)}</span><span class="mini__meta">${esc(t.role)}, ${esc(t.place)} · ${esc(t.when)}${ev}</span></li>`;
    })
    .join('');
  const tk = talks
    .map((t) => `<li><a class="mini__title" href="${t.pdf}" target="_blank" rel="noopener">${esc(t.title)}</a><span class="mini__meta">${esc(t.venue)}, ${esc(t.place)} · ${esc(t.when)}</span></li>`)
    .join('');
  const pt = patents.map((p) => `<li><span class="mini__title">${esc(p.title)}</span><span class="mini__meta">${esc(p.id)} · ${p.year}</span></li>`).join('');
  return `
    <section class="path" id="path" data-state="career" data-accent="#ffd27c" aria-labelledby="h-path">
      <div class="path__inner">
        <h2 class="section-title" id="h-path" data-strain data-text="Path">Path</h2>
        <p class="section-lede" data-reveal>A career, read as growth rings: one ring for every year since 2012. Hover a step to find its ring.</p>
        <ol class="steps" data-no-indent>${items}</ol>
        <div class="minis">
          <div class="mini" data-reveal><h3>Funded projects</h3><ul>${proj}</ul></div>
          <div class="mini" data-reveal><h3>Teaching</h3><ul>${teach}</ul><h3>Talks</h3><ul>${tk}</ul><h3>Patents</h3><ul>${pt}</ul><h3>Tools</h3><ul>${profile.tools.map((t) => `<li><span class="mini__meta">${esc(t)}</span></li>`).join('')}</ul></div>
        </div>
      </div>
    </section>`;
}

