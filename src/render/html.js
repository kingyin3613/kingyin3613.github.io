// Renders the narrative, publications and path into index.html at build time,
// so the page is complete, fast and indexable without JavaScript.
import { profile } from '../data/profile.js';
import { chapters } from '../data/chapters.js';
import { publications, themes } from '../data/publications.js';
import { path, projects, teaching, talks, patents } from '../data/path.js';
import { starters } from '../data/prompts.js';
import { glyph } from './glyphs.js';

export const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function chapterHTML(c) {
  const notes = c.notes.length
    ? `<ul class="notes" data-reveal>${c.notes
        .map((n) => `<li>${n.ref ? `<a href="#pub-${n.ref}" data-pub-link="${n.ref}">${esc(n.text)}</a>` : esc(n.text)}</li>`)
        .join('')}</ul>`
    : '';
  const crack = c.id === 'fracture' ? ' data-crack-title' : '';
  const extra = c.id === 'ask' ? askInline() : '';
  return `
    <section class="chapter chapter--${c.id}" id="${c.id}" data-state="${c.state}" data-accent="${c.accent}" aria-labelledby="h-${c.id}">
      <div class="chapter__inner">
        <p class="chapter__era" data-reveal>${esc(c.era)}</p>
        <h2 class="chapter__title" id="h-${c.id}" data-text="${esc(c.title)}" data-strain${crack}>${esc(c.title)}</h2>
        <p class="chapter__lede" data-reveal>${esc(c.lede)}</p>
        <div class="chapter__body">${c.paras.map((p) => `<p data-reveal>${esc(p)}</p>`).join('')}</div>
        ${notes}${extra}
      </div>
    </section>`;
}

