export function renderSections(html) {
  const before = chapters.filter((c) => c.id !== 'ask').map(chapterHTML).join('');
  const ask = chapterHTML(chapters.find((c) => c.id === 'ask'));
  const rail = chapters
    .map((c) => `<li><a href="#${c.id}" data-rail="${c.id}"><span class="rail__tick"></span><span class="rail__label">${esc(c.title)}</span></a></li>`)
    .join('');
  return html
    .replace('<!--HERO_TITLE-->', esc(profile.hero.title))
    .replace('<!--HERO_SUB-->', esc(profile.hero.sub))
    .replace('<!--HERO_HINT-->', esc(profile.hero.hint))
    .replace('<!--RAIL-->', rail)
    .replace('<!--CHAPTERS-->', before + labHTML() + ask)
    .replace('<!--PUBLICATIONS-->', publicationsHTML())
    .replace('<!--PATH-->', pathHTML())
    .replace('<!--CONTACT-->', contactHTML());
}
